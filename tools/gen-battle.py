#!/usr/bin/env python3
"""Generates Battle.js (EV yields, legendaries, type chart, move effects) from the PokeAPI CSV dump.

Usage: tools/gen-battle.py [csv-dir]
Missing CSV files are downloaded from github.com/PokeAPI/pokeapi into csv-dir
(default: a temporary directory). Run from anywhere; writes ../Battle.js.
"""
import csv, json, os, re, sys, tempfile, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/"
FLAGS = {"contact": 1, "charge": 2, "recharge": 4, "punch": 8, "sound": 16, "bite": 32,
         "pulse": 64, "ballistics": 128, "powder": 256, "heal": 512, "defrost": 1024, "dance": 2048}
# Effect ids we need to tell apart from their meta data.
BADLY_POISON = {"34", "203"}


def rows(folder, name):
    path = os.path.join(folder, name + ".csv")
    if not os.path.exists(path):
        print("downloading", name, file=sys.stderr)
        urllib.request.urlretrieve(BASE + name + ".csv", path)
    with open(path, newline="", encoding="utf-8") as f:
        yield from csv.DictReader(f)


def num(v, default=0):
    return int(v) if v not in ("", None) else default


def main():
    folder = sys.argv[1] if len(sys.argv) > 1 else tempfile.mkdtemp()
    os.makedirs(folder, exist_ok=True)

    # Our slugs come from pokemon-colorscripts; match them by National Dex number.
    info = open(os.path.join(ROOT, "Info.js"), encoding="utf-8").read()
    species = json.loads(re.search(r"^var species = (\{.*\})$", info, re.M).group(1))
    slug_of = {str(v[0]): k for k, v in species.items()}
    moves_js = open(os.path.join(ROOT, "Moves.js"), encoding="utf-8").read()
    used_moves = set(json.loads(re.search(r"^var moves = (\{.*\})$", moves_js, re.M).group(1)))

    pokemon_of = {}
    for r in rows(folder, "pokemon"):
        if r["is_default"] == "1" and r["species_id"] in slug_of:
            pokemon_of[r["id"]] = slug_of[r["species_id"]]

    # EV yield, as six digits (HP, Atk, Def, SpA, SpD, Spe).
    effort = {}
    for r in rows(folder, "pokemon_stats"):
        slug = pokemon_of.get(r["pokemon_id"])
        if slug:
            effort.setdefault(slug, [0] * 6)[int(r["stat_id"]) - 1] = int(r["effort"])
    evs = {s: "".join(str(v) for v in effort.get(s, [0] * 6)) for s in species}

    legendary = {}
    for r in rows(folder, "pokemon_species"):
        slug = slug_of.get(r["id"])
        if slug and (r["is_legendary"] == "1" or r["is_mythical"] == "1"):
            legendary[slug] = 2 if r["is_mythical"] == "1" else 1

    type_name = {r["id"]: r["identifier"] for r in rows(folder, "types")}
    chart = {}
    for r in rows(folder, "type_efficacy"):
        f = int(r["damage_factor"])
        if f != 100:
            chart.setdefault(type_name[r["damage_type_id"]], {})[type_name[r["target_type_id"]]] = f / 100

    flag_name = {r["id"]: r["identifier"] for r in rows(folder, "move_flags")}
    flags = {}
    for r in rows(folder, "move_flag_map"):
        bit = FLAGS.get(flag_name.get(r["move_flag_id"]))
        if bit:
            flags[r["move_id"]] = flags.get(r["move_id"], 0) | bit

    stat_changes = {}
    for r in rows(folder, "move_meta_stat_changes"):
        # PokeAPI stat ids: 2 Atk .. 6 Spe, 7 accuracy, 8 evasion -> our indexes 1..7
        stat_changes.setdefault(r["move_id"], []).append([int(r["stat_id"]) - 1, int(r["change"])])

    base = {r["id"]: r for r in rows(folder, "moves")}
    moves = {}
    for r in rows(folder, "move_meta"):
        mid = r["move_id"]
        if mid not in used_moves:
            continue
        b = base[mid]
        ailment = num(r["meta_ailment_id"])
        if ailment == 5 and b["effect_id"] in BADLY_POISON:
            ailment = 99    # badly poisoned
        # [priority, target, meta category, ailment, ailment %, min hits, max hits,
        #  drain %, healing %, crit stage, flinch %, stat %, stat changes, flags, effect id]
        moves[mid] = [num(b["priority"]), num(b["target_id"]), num(r["meta_category_id"]), ailment,
                      num(r["ailment_chance"]), num(r["min_hits"]), num(r["max_hits"]), num(r["drain"]),
                      num(r["healing"]), num(r["crit_rate"]), num(r["flinch_chance"]), num(r["stat_chance"]),
                      stat_changes.get(mid, []), flags.get(mid, 0), num(b["effect_id"])]
    for mid in used_moves - set(moves):
        b = base.get(mid)
        if b:
            moves[mid] = [num(b["priority"]), num(b["target_id"]), 13, 0, 0, 0, 0, 0, 0, 0, 0, 0, [],
                          flags.get(mid, 0), num(b["effect_id"])]

    def dump(v):
        return json.dumps(v, ensure_ascii=False, separators=(",", ":"))

    out = [
        ".pragma library",
        "",
        "// Generated by tools/gen-battle.py from PokeAPI.",
        "// evs: slug -> EV yield, one digit per stat (HP, Atk, Def, SpA, SpD, Spe).",
        "var evs = " + dump(evs),
        "// legendary: slug -> 1 legendary, 2 mythical.",
        "var legendary = " + dump(legendary),
        "// types: attacking type -> { defending type: multiplier } (1 is left out).",
        "var types = " + dump(chart),
        "// moves: id -> [priority, target, meta category, ailment, ailment %, min hits, max hits,",
        "//               drain %, healing %, crit stage, flinch %, stat %, [[stat, change]], flags, effect id]",
        "// flags: " + ", ".join("%s %d" % kv for kv in FLAGS.items()),
        "var moves = " + dump(dict(sorted(moves.items(), key=lambda kv: int(kv[0])))),
        "",
    ]
    with open(os.path.join(ROOT, "Battle.js"), "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("Battle.js:", len(evs), "species,", len(legendary), "legendaries,", len(moves), "moves", file=sys.stderr)


if __name__ == "__main__":
    main()
